#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "${SCRIPT_DIR}/lib/common.sh"

TIPPECANOE_VERSION="${TIPPECANOE_VERSION:-2.79.0}"
TIPPECANOE_BINARY_URL="${TIPPECANOE_BINARY_URL:-}"
TIPPECANOE_SOURCE_TARBALL="${TIPPECANOE_SOURCE_TARBALL:-/tmp/tippecanoe.tar.gz}"
PMTILES_VERSION="${PMTILES_VERSION:-v1.31.2}"
BUILD_GLYPHS_CRATE="${BUILD_GLYPHS_CRATE:-versatiles_glyphs}"
BUILD_GLYPHS_BINARY="${BUILD_GLYPHS_BINARY:-versatiles_glyphs}"
BUILD_GLYPHS_VERSION="${BUILD_GLYPHS_VERSION:-0.10.1}"
MBGL_RENDERER_NPM_PACKAGE="${MBGL_RENDERER_NPM_PACKAGE:-mbgl-renderer@0.9.0}"
INSTALL_PREFIX="${INSTALL_PREFIX:-$HOME/.local}"
BIN_DIR="${BIN_DIR:-${INSTALL_PREFIX}/bin}"
BUILD_ROOT="${BUILD_ROOT:-/tmp/huavd-map-build-tools}"

export GOPATH="${GOPATH:-$HOME/go}"
export CARGO_HOME="${CARGO_HOME:-$HOME/.cargo}"
export PATH="${BIN_DIR}:${GOPATH}/bin:${CARGO_HOME}/bin:${PATH}"

jobs() {
  if command -v nproc >/dev/null 2>&1; then
    nproc
  elif command -v sysctl >/dev/null 2>&1; then
    sysctl -n hw.ncpu
  else
    printf '2\n'
  fi
}

require_tooling() {
  local missing=()
  local cmd
  for cmd in "$@"; do
    if ! command -v "${cmd}" >/dev/null 2>&1; then
      missing+=("${cmd}")
    fi
  done

  if ((${#missing[@]} > 0)); then
    log_error "missing setup helper command(s): ${missing[*]}"
    return 1
  fi
}

tool_version_line() {
  local cmd="$1"
  local version
  version="$(cmd_version "${cmd}" 2>/dev/null)"
  if [[ -n "${version}" ]]; then
    printf '%s\n' "${version}"
  else
    printf 'version unavailable\n'
  fi
}

already_installed() {
  local cmd="$1"
  local version
  if command -v "${cmd}" >/dev/null 2>&1; then
    version="$(tool_version_line "${cmd}")"
    if [[ "${version}" != "version unavailable" ]]; then
      log_info "${cmd} already installed: ${version}"
      return 0
    fi
    log_warn "${cmd} exists but is not runnable; reinstalling"
  fi
  return 1
}

platform_key() {
  local os arch
  os="$(uname -s)"
  arch="$(uname -m)"
  printf '%s/%s\n' "${os}" "${arch}"
}

download_file() {
  local url="$1"
  local output="$2"

  log_info "downloading ${url}"
  if ! wget -q -O "${output}" "${url}"; then
    log_warn "download failed: ${url}"
    return 1
  fi
}

github_release_asset_urls() {
  local owner="$1"
  local repo="$2"
  local tag="$3"
  local pattern="$4"
  local api_url="https://api.github.com/repos/${owner}/${repo}/releases/tags/${tag}"

  require_tooling wget jq || return 1

  log_info "querying GitHub release assets: ${owner}/${repo} ${tag}"
  wget -q -O - "${api_url}" \
    | jq -r --arg pattern "${pattern}" '.assets[]? | select(.name | test($pattern; "i")) | .browser_download_url'
}

install_binary_from_archive() {
  local archive="$1"
  local binary_name="$2"
  local extract_dir="$3"
  local binary_path

  mkdir -p "${extract_dir}"
  if ! tar -xzf "${archive}" -C "${extract_dir}"; then
    log_warn "failed to extract archive: ${archive}"
    return 1
  fi

  binary_path="$(find "${extract_dir}" -type f -name "${binary_name}" -print -quit)"
  if [[ -z "${binary_path}" ]]; then
    log_warn "archive does not contain ${binary_name}: ${archive}"
    return 1
  fi

  mkdir -p "${BIN_DIR}"
  if ! install -m 0755 "${binary_path}" "${BIN_DIR}/${binary_name}"; then
    log_error "failed to install ${binary_name} to ${BIN_DIR}/${binary_name}"
    return 1
  fi
}

install_binary_from_url() {
  local url="$1"
  local binary_name="$2"
  local download_path="$3"
  local extract_dir="$4"

  rm -rf "${extract_dir}"
  download_file "${url}" "${download_path}" || return 1

  if tar -tzf "${download_path}" >/dev/null 2>&1; then
    install_binary_from_archive "${download_path}" "${binary_name}" "${extract_dir}"
  else
    mkdir -p "${BIN_DIR}"
    if ! install -m 0755 "${download_path}" "${BIN_DIR}/${binary_name}"; then
      log_error "failed to install ${binary_name} to ${BIN_DIR}/${binary_name}"
      return 1
    fi
  fi
}

check_tippecanoe_build_deps() {
  local probe_dir="${BUILD_ROOT}/tippecanoe-build-deps"
  local probe_cpp="${probe_dir}/check.cpp"
  local probe_bin="${probe_dir}/check"
  local includes libs ldflags
  local include_flags lib_flags ld_flags

  require_tooling c++ || return 1
  includes="$(tippecanoe_make_includes)"
  libs="$(tippecanoe_make_libs)"
  ldflags="$(tippecanoe_make_ldflags "${libs}")"
  # Package paths generated by pkg-config/Nix do not contain spaces.
  # shellcheck disable=SC2206
  include_flags=(${includes})
  # shellcheck disable=SC2206
  lib_flags=(${libs})
  # shellcheck disable=SC2206
  ld_flags=(${ldflags})

  mkdir -p "${probe_dir}"
  printf '%s\n' \
    '#include <sqlite3.h>' \
    '#include <zlib.h>' \
    'int main(void) { sqlite3 *db = 0; (void)db; return Z_OK; }' \
    > "${probe_cpp}"

  if ! c++ "${include_flags[@]}" "${probe_cpp}" "${lib_flags[@]}" "${ld_flags[@]}" -lsqlite3 -lz -o "${probe_bin}" >/dev/null 2>&1; then
    log_error "tippecanoe build dependencies missing: sqlite3/zlib headers or libraries are not available"
    log_error "Ubuntu/Debian: sudo apt-get update && sudo apt-get install -y build-essential pkg-config libsqlite3-dev zlib1g-dev"
    log_error "devbox: ensure sqlite/zlib dev outputs are available, then run devbox install"
    log_error "override: TIPPECANOE_INCLUDES='-I/path/include ...' TIPPECANOE_LIBS='-L/path/lib ...' TIPPECANOE_LDFLAGS='-Wl,-rpath,/path/lib ...' devbox run setup"
    return 1
  fi

  if ! "${probe_bin}" >/dev/null 2>&1; then
    log_error "tippecanoe runtime dependencies missing: sqlite3/zlib shared libraries are not loadable"
    log_error "Ubuntu/Debian: sudo apt-get update && sudo apt-get install -y libsqlite3-0 zlib1g"
    log_error "override: TIPPECANOE_LDFLAGS='-Wl,-rpath,/path/lib ...' devbox run setup"
    return 1
  fi
}

append_unique_flag() {
  local flags="$1"
  local flag="$2"

  [[ -n "${flag}" ]] || {
    printf '%s\n' "${flags}"
    return
  }

  case " ${flags} " in
    *" ${flag} "*) printf '%s\n' "${flags}" ;;
    *) printf '%s %s\n' "${flags}" "${flag}" ;;
  esac
}

devbox_lock_package_paths() {
  local package="$1"
  local lock="${REPO_ROOT}/devbox.lock"

  [[ -f "${lock}" ]] || return 0
  command -v jq >/dev/null 2>&1 || return 0

  jq -r --arg package "${package}" '.packages[$package] | .. | objects | .path? // empty' "${lock}" \
    | while IFS= read -r path; do
        [[ -d "${path}" ]] && printf '%s\n' "${path}"
      done
}

devbox_lock_include_flags_for() {
  local package="$1"
  local header="$2"
  local path flags=""

  while IFS= read -r path; do
    [[ -f "${path}/include/${header}" ]] || continue
    flags="$(append_unique_flag "${flags}" "-I${path}/include")"
  done < <(devbox_lock_package_paths "${package}")

  printf '%s\n' "${flags}"
}

devbox_lock_lib_flags_for() {
  local package="$1"
  local lib_pattern="$2"
  local path flags=""
  local matches=()

  while IFS= read -r path; do
    [[ -d "${path}/lib" ]] || continue
    shopt -s nullglob
    matches=("${path}"/lib/${lib_pattern})
    shopt -u nullglob
    if ((${#matches[@]} > 0)); then
      flags="$(append_unique_flag "${flags}" "-L${path}/lib")"
    fi
  done < <(devbox_lock_package_paths "${package}")

  printf '%s\n' "${flags}"
}

using_nix_toolchain() {
  local cxx="${CXX:-c++}"
  local cxx_path resolved

  cxx_path="$(command -v "${cxx}" 2>/dev/null || true)"
  resolved="$(readlink -f "${cxx_path}" 2>/dev/null || printf '%s\n' "${cxx_path}")"

  [[ "${resolved}" == /nix/store/* || -n "${IN_NIX_SHELL:-}" || -n "${DEVBOX_SHELL_ENABLED:-}" || -n "${NIX_CC:-}" ]]
}

tippecanoe_make_includes() {
  local flags="-I. -Iclipper2/include"

  if command -v pkg-config >/dev/null 2>&1 && pkg-config --exists sqlite3 zlib; then
    flags="$(pkg-config --cflags sqlite3 zlib) ${flags}"
  fi
  if using_nix_toolchain; then
    flags="$(append_unique_flag "${flags}" "$(devbox_lock_include_flags_for 'sqlite@3.53.3' sqlite3.h)")"
    flags="$(append_unique_flag "${flags}" "$(devbox_lock_include_flags_for 'zlib@1.3.2' zlib.h)")"
  else
    flags="$(append_unique_flag "${flags}" "-I/usr/local/include")"
    flags="$(append_unique_flag "${flags}" "-I/usr/include")"
  fi

  printf '%s\n' "${TIPPECANOE_INCLUDES:-${flags}}"
}

tippecanoe_make_libs() {
  local flags=""

  if command -v pkg-config >/dev/null 2>&1 && pkg-config --exists sqlite3 zlib; then
    flags="$(pkg-config --libs-only-L --libs-only-other sqlite3 zlib) ${flags}"
  fi
  if using_nix_toolchain; then
    flags="$(append_unique_flag "${flags}" "$(devbox_lock_lib_flags_for 'sqlite@3.53.3' 'libsqlite3.so*')")"
    flags="$(append_unique_flag "${flags}" "$(devbox_lock_lib_flags_for 'zlib@1.3.2' 'libz.so*')")"
  else
    flags="$(append_unique_flag "${flags}" "-L/usr/local/lib")"
    if [[ -d /usr/lib/x86_64-linux-gnu ]]; then
      flags="$(append_unique_flag "${flags}" "-L/usr/lib/x86_64-linux-gnu")"
    fi
    if [[ -d /lib/x86_64-linux-gnu ]]; then
      flags="$(append_unique_flag "${flags}" "-L/lib/x86_64-linux-gnu")"
    fi
  fi

  printf '%s\n' "${TIPPECANOE_LIBS:-${flags}}"
}

tippecanoe_make_ldflags() {
  local libs="$1"
  local flags="${TIPPECANOE_LDFLAGS:-}"
  local token dir

  for token in ${libs}; do
    case "${token}" in
      -L*)
        dir="${token#-L}"
        [[ -d "${dir}" ]] || continue
        flags="$(append_unique_flag "${flags}" "-Wl,-rpath,${dir}")"
        ;;
    esac
  done

  printf '%s\n' "${flags}"
}

try_install_osmium_binary() {
  if command -v apt-get >/dev/null 2>&1 && command -v sudo >/dev/null 2>&1; then
    log_info "trying osmium-tool install via apt-get"
    if sudo apt-get update && sudo apt-get install -y osmium-tool; then
      log_info "osmium installed via apt-get"
      return 0
    fi
    log_warn "apt-get install failed for osmium-tool"
  fi

  if command -v brew >/dev/null 2>&1; then
    log_info "trying osmium-tool install via brew"
    if brew install osmium-tool; then
      log_info "osmium installed via brew"
      return 0
    fi
    log_warn "brew install failed for osmium-tool"
  fi

  return 1
}

install_osmium_from_source() {
  local src_dir="${BUILD_ROOT}/osmium-tool"

  require_tooling git cmake || return 1

  log_warn "falling back to osmium-tool source build"
  rm -rf "${src_dir}"
  mkdir -p "${BUILD_ROOT}"

  if ! git clone --depth=1 https://github.com/osmcode/osmium-tool.git "${src_dir}"; then
    log_error "failed to clone osmium-tool source"
    return 1
  fi

  if ! (
    cd "${src_dir}"
    mkdir -p build
    cd build
    cmake -DCMAKE_BUILD_TYPE=Release -DCMAKE_INSTALL_PREFIX="${INSTALL_PREFIX}" ..
    cmake --build . -j"$(jobs)"
    cmake --install .
  ); then
    log_error "osmium-tool source build failed"
    return 1
  fi

  rm -rf "${src_dir}"
}

install_osmium() {
  already_installed osmium && return 0
  log_info "installing osmium-tool"

  if try_install_osmium_binary || install_osmium_from_source; then
    already_installed osmium || {
      log_error "osmium installation completed but command is not on PATH"
      return 1
    }
    return 0
  fi

  log_error "osmium installation failed"
  return 1
}

try_install_tippecanoe_binary() {
  local archive extract_dir

  if [[ -z "${TIPPECANOE_BINARY_URL}" ]]; then
    log_info "TIPPECANOE_BINARY_URL is not set; using official source tarball"
    return 1
  fi

  require_tooling wget tar find install || return 1

  archive="${BUILD_ROOT}/tippecanoe-${TIPPECANOE_VERSION}.tar.gz"
  extract_dir="${BUILD_ROOT}/tippecanoe-bin"

  mkdir -p "${BUILD_ROOT}"
  log_info "trying tippecanoe binary from TIPPECANOE_BINARY_URL"
  install_binary_from_url "${TIPPECANOE_BINARY_URL}" tippecanoe "${archive}" "${extract_dir}"
}

install_tippecanoe_from_source() {
  local archive="${BUILD_ROOT}/tippecanoe-${TIPPECANOE_VERSION}-source.tar.gz"
  local src_dir="${BUILD_ROOT}/tippecanoe"
  local source_url="${TIPPECANOE_SOURCE_URL:-https://github.com/felt/tippecanoe/archive/refs/tags/${TIPPECANOE_VERSION}.tar.gz}"
  local make_includes make_libs make_ldflags

  require_tooling tar make install || return 1

  log_warn "falling back to tippecanoe source build"
  rm -rf "${src_dir}"
  mkdir -p "${BUILD_ROOT}"
  make_includes="$(tippecanoe_make_includes)"
  make_libs="$(tippecanoe_make_libs)"
  make_ldflags="$(tippecanoe_make_ldflags "${make_libs}")"
  check_tippecanoe_build_deps || return 1

  if [[ -f "${TIPPECANOE_SOURCE_TARBALL}" ]]; then
    if ! tar -tzf "${TIPPECANOE_SOURCE_TARBALL}" >/dev/null 2>&1; then
      log_error "local tippecanoe source tarball is not readable: ${TIPPECANOE_SOURCE_TARBALL}"
      return 1
    fi
    log_info "using local tippecanoe source tarball ${TIPPECANOE_SOURCE_TARBALL}"
    archive="${TIPPECANOE_SOURCE_TARBALL}"
  else
    require_tooling wget || return 1
    log_info "downloading tippecanoe source from ${source_url}"
    if ! download_file "${source_url}" "${archive}"; then
      log_error "failed to download tippecanoe source tarball ${TIPPECANOE_VERSION}"
      return 1
    fi
  fi

  mkdir -p "${src_dir}"
  if ! tar -xzf "${archive}" -C "${src_dir}" --strip-components=1; then
    log_error "failed to extract tippecanoe source tarball"
    return 1
  fi

  if ! (
    cd "${src_dir}"
    make -j"$(jobs)" INCLUDES="${make_includes}" LIBS="${make_libs}" LDFLAGS="${make_ldflags}"
  ); then
    log_error "tippecanoe source build failed"
    return 1
  fi

  mkdir -p "${BIN_DIR}"
  if ! install -m 0755 "${src_dir}/tippecanoe" "${BIN_DIR}/tippecanoe"; then
    log_error "failed to install tippecanoe to ${BIN_DIR}/tippecanoe"
    return 1
  fi
  rm -rf "${src_dir}"
}

install_tippecanoe() {
  already_installed tippecanoe && return 0
  log_info "installing tippecanoe ${TIPPECANOE_VERSION}"

  if try_install_tippecanoe_binary || install_tippecanoe_from_source; then
    already_installed tippecanoe || {
      log_error "tippecanoe installation completed but command is not on PATH"
      return 1
    }
    return 0
  fi

  log_error "tippecanoe installation failed"
  return 1
}

pmtiles_binary_urls() {
  local version_no_v="${PMTILES_VERSION#v}"
  local urls
  case "$(platform_key)" in
    Linux/x86_64|Linux/amd64)
      if urls="$(github_release_asset_urls protomaps go-pmtiles "${PMTILES_VERSION}" '(pmtiles|go-pmtiles).*linux.*(x86_64|amd64).*\.tar\.gz$')"; then
        printf '%s\n' "${urls}"
      else
        log_warn "GitHub release asset lookup failed for pmtiles; trying fixed URLs"
      fi
      printf '%s\n' \
        "https://github.com/protomaps/go-pmtiles/releases/download/${PMTILES_VERSION}/go-pmtiles_${version_no_v}_Linux_x86_64.tar.gz" \
        "https://github.com/protomaps/go-pmtiles/releases/download/${PMTILES_VERSION}/pmtiles_${version_no_v}_linux_x86_64.tar.gz" \
        "https://github.com/protomaps/go-pmtiles/releases/download/${PMTILES_VERSION}/pmtiles_${version_no_v}_Linux_x86_64.tar.gz"
      ;;
    Darwin/arm64)
      if urls="$(github_release_asset_urls protomaps go-pmtiles "${PMTILES_VERSION}" '(pmtiles|go-pmtiles).*(darwin|macos).*arm64.*\.tar\.gz$')"; then
        printf '%s\n' "${urls}"
      else
        log_warn "GitHub release asset lookup failed for pmtiles; trying fixed URLs"
      fi
      printf '%s\n' \
        "https://github.com/protomaps/go-pmtiles/releases/download/${PMTILES_VERSION}/go-pmtiles_${version_no_v}_Darwin_arm64.tar.gz" \
        "https://github.com/protomaps/go-pmtiles/releases/download/${PMTILES_VERSION}/pmtiles_${version_no_v}_darwin_arm64.tar.gz"
      ;;
    Darwin/x86_64)
      if urls="$(github_release_asset_urls protomaps go-pmtiles "${PMTILES_VERSION}" '(pmtiles|go-pmtiles).*(darwin|macos).*(x86_64|amd64).*\.tar\.gz$')"; then
        printf '%s\n' "${urls}"
      else
        log_warn "GitHub release asset lookup failed for pmtiles; trying fixed URLs"
      fi
      printf '%s\n' \
        "https://github.com/protomaps/go-pmtiles/releases/download/${PMTILES_VERSION}/go-pmtiles_${version_no_v}_Darwin_x86_64.tar.gz" \
        "https://github.com/protomaps/go-pmtiles/releases/download/${PMTILES_VERSION}/pmtiles_${version_no_v}_darwin_x86_64.tar.gz"
      ;;
  esac
}

try_install_pmtiles_binary() {
  local archive extract_dir url urls

  require_tooling wget tar find install || return 1

  mkdir -p "${BUILD_ROOT}"
  urls="$(pmtiles_binary_urls)"
  while IFS= read -r url; do
    [[ -n "${url}" ]] || continue
    archive="${BUILD_ROOT}/pmtiles-${PMTILES_VERSION}.tar.gz"
    extract_dir="${BUILD_ROOT}/pmtiles-bin"
    rm -rf "${extract_dir}"

    if download_file "${url}" "${archive}" && install_binary_from_archive "${archive}" pmtiles "${extract_dir}"; then
      return 0
    fi
  done <<< "${urls}"

  log_warn "no pmtiles pre-built binary matched $(platform_key)"
  return 1
}

