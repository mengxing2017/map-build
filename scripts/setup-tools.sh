ensure_cargo_toolchain() {
  if command -v cargo >/dev/null 2>&1; then
    return 0
  fi

  if command -v rustup >/dev/null 2>&1; then
    log_info "installing Rust stable toolchain with rustup"
    rustup default stable || return 1
  fi

  require_tooling cargo || return 1
}

install_build_glyphs() {
  if command -v build-glyphs >/dev/null 2>&1; then
    log_info "build-glyphs already installed: $(tool_version_line build-glyphs)"
    return 0
  fi

  if ! command -v "${BUILD_GLYPHS_BINARY}" >/dev/null 2>&1; then
    ensure_cargo_toolchain || {
      log_error "cargo is required to install build-glyphs; run setup inside devbox"
      return 1
    }

    log_info "installing glyph generator with cargo crate ${BUILD_GLYPHS_CRATE}${BUILD_GLYPHS_VERSION:+ ${BUILD_GLYPHS_VERSION}}"
    local cargo_args=("${BUILD_GLYPHS_CRATE}")
    if [[ -n "${BUILD_GLYPHS_VERSION}" ]]; then
      cargo_args+=(--version "${BUILD_GLYPHS_VERSION}")
    fi

    if ! cargo install "${cargo_args[@]}"; then
      log_error "glyph generator cargo install failed"
      return 1
    fi
  fi

  command -v "${BUILD_GLYPHS_BINARY}" >/dev/null 2>&1 || {
    log_error "glyph generator installation completed but ${BUILD_GLYPHS_BINARY} is not on PATH"
    return 1
  }

  mkdir -p "${BIN_DIR}"
  if ! cat > "${BIN_DIR}/build-glyphs" <<EOF
#!/usr/bin/env bash
set -euo pipefail

if [[ "\${1:-}" == "--version" || "\${1:-}" == "-V" ]]; then
  exec ${BUILD_GLYPHS_BINARY} --version
fi

if [[ "\$#" -ne 2 ]]; then
  printf 'usage: build-glyphs <font-file> <output-dir>\\n' >&2
  exit 2
fi

exec ${BUILD_GLYPHS_BINARY} merge -o "\$2/glyphs" "\$1"
EOF
  then
    log_error "failed to write build-glyphs wrapper to ${BIN_DIR}/build-glyphs"
    return 1
  fi
  if ! chmod 0755 "${BIN_DIR}/build-glyphs"; then
    log_error "failed to make build-glyphs wrapper executable: ${BIN_DIR}/build-glyphs"
    return 1
  fi

  log_info "build-glyphs installed: $(tool_version_line build-glyphs)"
}

install_mbgl_render() {
  if command -v mbgl-render >/dev/null 2>&1; then
    log_info "mbgl-render already installed: $(tool_version_line mbgl-render)"
    write_mbgl_render_wrapper || return 1
    return 0
  fi

  if command -v pnpm >/dev/null 2>&1; then
    log_info "installing mbgl-render CLI from npm package ${MBGL_RENDERER_NPM_PACKAGE}"
    if pnpm add -g "${MBGL_RENDERER_NPM_PACKAGE}"; then
      mbgl_render_npm_bin_path >/dev/null || {
        log_error "${MBGL_RENDERER_NPM_PACKAGE} installation completed but npm CLI target was not found"
        return 1
      }
      write_mbgl_render_wrapper || return 1
      return 0
    fi
    log_warn "pnpm global install failed for ${MBGL_RENDERER_NPM_PACKAGE}"
  fi

  if command -v npm >/dev/null 2>&1; then
    log_info "installing mbgl-render CLI from npm package ${MBGL_RENDERER_NPM_PACKAGE}"
    if npm install -g "${MBGL_RENDERER_NPM_PACKAGE}"; then
      mbgl_render_npm_bin_path >/dev/null || {
        log_error "${MBGL_RENDERER_NPM_PACKAGE} installation completed but npm CLI target was not found"
        return 1
      }
      write_mbgl_render_wrapper || return 1
      return 0
    fi
    log_warn "npm global install failed for ${MBGL_RENDERER_NPM_PACKAGE}"
  fi

  log_warn "mbgl-render is not installed; raster bake needs npm package mbgl-renderer or MBGL_RENDER_TILE_COMMAND"
  return 0
}

mbgl_render_npm_bin_path() {
  command -v npm >/dev/null 2>&1 || return 1
  local npm_root npm_prefix candidate
  npm_prefix="$(npm prefix -g 2>/dev/null || true)"
  if [[ -n "${npm_prefix}" ]]; then
    candidate="${npm_prefix}/bin/mbgl-render"
    if [[ -x "${candidate}" && "${candidate}" != "${BIN_DIR}/mbgl-render" ]]; then
      printf '%s\n' "${candidate}"
      return 0
    fi
  fi

  npm_root="$(npm root -g 2>/dev/null || true)"
  if [[ -n "${npm_root}" && -f "${npm_root}/mbgl-renderer/dist/cli.js" ]]; then
    printf '%s\n' "${npm_root}/mbgl-renderer/dist/cli.js"
    return 0
  fi

  return 1
}

append_ld_dir() {
  local current="$1"
  local dir="$2"
  [[ -d "${dir}" ]] || {
    printf '%s\n' "${current}"
    return
  }
  case ":${current}:" in
    *":${dir}:"*) printf '%s\n' "${current}" ;;
    *) printf '%s:%s\n' "${current}" "${dir}" ;;
  esac
}

mbgl_render_ld_library_path() {
  local current="$1"
  shift
  local package path
  for package in "$@"; do
    while IFS= read -r path; do
      [[ -n "${path}" ]] || continue
      current="$(append_ld_dir "${current}" "${path}/lib")"
    done < <(devbox_lock_package_paths "${package}")
  done
  printf '%s\n' "${current}"
}

